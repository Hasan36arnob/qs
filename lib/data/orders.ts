const SHIPPING = 80;

// Quick lookup so we can build OrderItems from product ids without re-typing
// names/prices/images (keeps the data below in sync with products.ts).
const productMap = new Map(products.map((p) => [p.id, p]));

function item(productId: string, quantity = 1, variant?: string): OrderItem {
  const p = productMap.get(productId);
  if (!p) throw new Error(`Unknown product id: ${productId}`);
  return {
    productId: p.id,
    name: p.name,
    price: p.price,
    quantity,
    variant,
    image: p.images[0],
  };
}

function subtotalOf(items: OrderItem[]): number {
  return items.reduce((sum, i) => sum + i.price * i.quantity, 0);
}

function makeOrder(
  id: string,
  opts: {
    items: OrderItem[];
    status: OrderStatus;
    source: OrderSource;
    paymentMethod: 'cod' | 'card' | 'mobile-banking';
    address: Address;
    createdAt: string;
    updatedAt?: string;
    userId?: string;
    sessionId?: string;
    utm?: { source?: string; medium?: string; campaign?: string; content?: string };
  },
): Order {
  const subtotal = subtotalOf(opts.items);
  const total = subtotal + SHIPPING;
  return {
    id,
    userId: opts.userId,
    sessionId: opts.sessionId,
    items: opts.items,
    status: opts.status,
    subtotal,
    shipping: SHIPPING,
    total,
    shippingAddress: opts.address,
    paymentMethod: opts.paymentMethod,
    source: opts.source,
    utm: opts.utm,
    createdAt: opts.createdAt,
    updatedAt: opts.updatedAt ?? opts.createdAt,
  };
}

