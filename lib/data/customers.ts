/**
 * Simulate network latency for async fetch helpers.
 */
const SIMULATED_DELAY_MS = 300;

const delay = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));

/**
 * Fetch all customers, with a small simulated network delay.
 * Returns a shallow copy so callers can't mutate the source array.
 */
export async function fetchCustomers(): Promise<Customer[]> {
  await delay(SIMULATED_DELAY_MS);
  return customers.map((customer) => ({ ...customer }));
}

/**
 * Fetch a single customer by id, with a small simulated network delay.
 * Returns `undefined` when no customer matches the given id.
 */
export async function fetchCustomerById(id: string): Promise<Customer | undefined> {
  await delay(SIMULATED_DELAY_MS);
  const customer = customers.find((c) => c.id === id);
  return customer ? { ...customer } : undefined;
}
